wchar_t* Text::ConvertWordsToBig(wchar_t* str) {
    for (wchar_t* i = str; *i; ++i) {
        *i = this->ConvertToUpper(*i);
    }
    return L" ";
}


wchar_t Text::ConvertToUpper(wchar_t str) {

    switch (this->Language) {
    case 'e':
        if (str >= 'a' && str <= 'z')
            str=str - 32;
        break;
    case 'f':
        if (str >= 'a' && str <= 'z')
            str = str - 32;
        else  if (str >= 128 && str <= 255)
            str = gFontJapan[str];
        break;
    case 'g':
    case 'i':
    case 's':
        if (str >= 'a' && str <= 'z')
            str = str - 32;
        else if (str >= 128 && str <= 255)
            str = gFontEnglish[str];
        break;
    case 'r':
        if (str >= 'a' && str <= 'z')
            str = str - 32;
        if (str >= 'а' && str <= 'п')
            str = str - 32;
        if (str >= 'р' && str <= 'я')
            str = str - 80;
        if (str >= 'ё' )
            str = 'Ё';
         break;
    default:
        return str;
    }
    return str;
}


