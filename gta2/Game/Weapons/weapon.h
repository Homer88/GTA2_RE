// ============================================================================
// Weapon — параметры одного экземпляра оружия (S74, 0x30 байт)
//
// Хардкодные таблицы в бинарнике:
//   ARRAY_00575904[28] — макс. отображаемое кол-во патронов (raw = ×10)
//     Все 99 (0x63), кроме CAR_BOMB = 1
//   ARRAY_00575920[28] — кол-во патронов за подбор (raw = ×10)
//     [0]=10, [1]=10, [2]=5, [3]=20, [4]=5, [5]=5, [6]=10, [7]=20,
//     [8]=20, [9]=10, [10]=10, [11..14]=0, [15]=1, [16]=5, [17]=5,
//     [18]=10, [19]=50, [20]=50, [21]=20, [22]=50, [23]=1, [24..27]=0
//
// Формула отображения: display = (Ammo + 9) / 10; Ammo == 0xFFFF = ∞
// Формула записи: Ammo = display_value × 10
// ============================================================================
struct Weapon
{
    // +0x00: Текущий боезапас (сырое значение, отображаемое = Ammo/10)
    // 0xFFFF = бесконечные патроны, 0 = нет патронов
    unsigned short Ammo;

    // +0x02: Таймер перезарядки (в кадрах).
    // При выстреле устанавливается, каждый кадр уменьшается на 1.
    // Когда = 0, оружие может стрелять снова.
    // При POWERUP_FAST_RELOAD делится на 2 (см. Weapon::TimeToReload).
    char TimeToReload;

    // +0x03: Неизвестно. Инициализируется 0. Не читается в декомпилированном коде.
    char field_3;

    // +0x04: Режим стрельбы (быстрый / медленный).
    // 0 = медленный режим (обычный огонь, TimeToReload = 20-50 кадров).
    // Ненулевое = быстрый режим (SMG, TimeToReload = 5 кадров).
    // Также используется как указатель на данные вращения для некоторых
    // типов оружия (см. Weapon::sub_4CE970).
    int SMG;

    // +0x08: Неизвестно. Инициализируется 0. Обнуляется при деинициализации.
    int field_8;

    // +0x0C: Неизвестно. Инициализируется -1 (0xFFFFFFFF).
    int field_C;

    // +0x10: Неизвестно. Инициализируется 0. Не читается в декомпилированном коде.
    short field_10;

    // +0x12: Неизвестно.
    char field_12;

    // +0x13: Неизвестно.
    char field_13;

    // +0x14: Машина, к которой привязано оружие.
    // Для пехотного оружия = NULL. Для оружия турели = указатель на Car.
    Car* Car;

    // +0x18: Указатель на следующее оружие в связанном списке WeaponDatabase.
    // WeaponDatabase::sWeapon (активный список) и WeaponDatabase::NextWeapon
    // (свободный список) образуют два связных списка.
    Weapon* NextWeapon;

    // +0x1C: Тип оружия (enum WeaponType, 0-28).
    WeaponType TypeWeapon;

    // +0x20: Фаза стрельбы / состояние "уже стрелял".
    // У дробовика чередуется 0/1 (левый/правый ствол).
    // У огнемёта используется как переключатель фаз (0=одна, 1=другая).
    char field_20;

    // +0: Флаг "попадание".
    // Устанавливается в 1, когда снаряд попал во что-то (Projectile::Hit).
    // Сбрасывается в 0 перед каждым выстрелом.
    char field_21;

    // +0x22: Неизвестно.
    char field_22;

    // +0x23: Неизвестно.
    char field_23;

    // +0x24: Указатель на владельца (Ped).
    // Для пехотного оружия = владелец-пешеход.
    // Для турелей = водитель машины (Car::GetDriver).
    Ped* Ped;

    // +0x28: Звуковой дескриптор (DMAudio::S157_FUN_00410750).
    // Создаётся при инициализации, уничтожается при деинициализации.
    int SoundWeapon;

    // +0x2C: Флаг "только что стрелял" (Set_4CCA80).
    // Устанавливается в 1 после каждого выстрела.
    // Используется для предотвращения повторной анимации.
    char field_2C;

    // +0x2D: Неизвестно.
    char field_2D;

    // +0x2E: Неизвестно.
    char field_2E;

    // +0x2F: Неизвестно.
    char field_2F;
};

// ============================================================================
// WeaponDatabase — пул управления оружием (S73, 0x2FDC байт)
//
// Хранит 255 оружий в массиве и управляет двумя связными списками:
//   sWeapon (активные) и NextWeapon (свободные).
//
// Память выделяется одним блоком: operator_new(0x2FDC).
// Деструктор: _eh_vector_destructor_iterator_(base+8, 0x30, 0xFF, Weapon::~S74)
// ============================================================================
struct WeaponDatabase
{
    // +0x00: Голова связанного списка активных оружий.
    Weapon* sWeapon;

    // +0x04: Голова связанного списка свободных оружий (пул).
    Weapon* NextWeapon;

    // +0x08: Массив-пул из 255 оружий (255 × 0x30 = 0x2F40 байт).
    Weapon sWeapon_Arr255[255];

    // +0x2FD8: Неизвестно (подозрение: счётчик активных оружий).
    short field_2FD8;

    // +0x2FDA: Неизвестно.
    char field_2FDA;

    // +0x2FDB: Неизвестно.
    char field_2FDB;
};

// ============================================================================
// Arsenal — турельная система (S72, 0x08 байт)
//
// Используется как Gun turret container для машин.
// Глобальный экземпляр: gArsenal (один на мир).
// ============================================================================
struct Arsenal
{
    // +0x00: Спрайт/визуальный указатель турели.
    void* Sprite;

    // +0x04: Количество привязанных оружий.
    short Count;

    // +0x06: Неизвестно.
    short field_6;
};

