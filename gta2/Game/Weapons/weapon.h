// weapon.h — Структуры оружия GTA2
// Восстановлено из реверс-инжиниринга бинарника gta2.exe (IDA + Ghidra).
//
// Размеры подтверждены:
//   Weapon       = 0x30 (48) байт
//   WeaponDatabase = 0x2FDC (12252) байт — пул из 255 оружий
//   Arsenal      = 0x08 (8) байт
// ============================================================================

// Forward declarations
